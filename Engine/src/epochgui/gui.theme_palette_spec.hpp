    [[nodiscard]] constexpr std::uint32_t packed_rgb(Rgb color) noexcept
    {
        return (std::uint32_t{color.r} << 16)
            | (std::uint32_t{color.g} << 8)
            | std::uint32_t{color.b};
    }

    // Headings follow the palette's selection hue, with readable contrast on
    // their actual panel surface. Status colors remain independent semantics.
    [[nodiscard]] inline Rgb section_heading_color(const Palette& palette) noexcept
    {
        const auto luminance = [](Rgb color) noexcept {
            const auto linear = [](std::uint8_t channel) noexcept {
                const double value = channel / 255.0;
                return value <= 0.04045 ? value / 12.92
                    : std::pow((value + 0.055) / 1.055, 2.4);
            };
            return 0.2126 * linear(color.r) + 0.7152 * linear(color.g)
                + 0.0722 * linear(color.b);
        };
        const double background = luminance(palette.panel);
        Rgb color = palette.active;
        color.a = 255;
        for (unsigned attempt = 0; attempt < 9; ++attempt)
        {
            const double foreground = luminance(color);
            const double contrast = foreground > background
                ? (foreground + 0.05) / (background + 0.05)
                : (background + 0.05) / (foreground + 0.05);
            if (contrast >= 4.5) return color;
            const auto blend = [light = palette.isLight](std::uint8_t channel) noexcept {
                return static_cast<std::uint8_t>(light ? channel / 2u
                    : (static_cast<unsigned>(channel) + 255u) / 2u);
            };
            color = {blend(color.r), blend(color.g), blend(color.b), 255};
        }
        return palette.isLight ? Rgb{0, 0, 0, 255} : Rgb{255, 255, 255, 255};
    }

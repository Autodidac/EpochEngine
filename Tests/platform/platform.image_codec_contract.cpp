// CPU-only image decode contract; no clipboard, window or renderer access.
#include "../../Engine/src/platform/platform.image_codec_win.hpp"
#include <cassert>
#include <string_view>
int main()
{
    constexpr unsigned char png[]{0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x04, 0x00, 0x00, 0x00, 0xb5, 0x1c, 0x0c, 0x02, 0x00, 0x00, 0x00, 0x0b, 0x49, 0x44, 0x41, 0x54, 0x78, 0xda, 0x63, 0xfc, 0xff, 0x1f, 0x00, 0x03, 0x03, 0x02, 0x00, 0xef, 0xa3, 0x4b, 0x51, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82};
    const std::string_view bytes{reinterpret_cast<const char*>(png), sizeof(png)};
    const auto image = epochengine::platform_image_codec::decode_thumbnail(bytes);
    assert(image.width == 1u && image.height == 1u && image.rgba.size() == 4u);
    assert(epochengine::platform_image_codec::decode_thumbnail("broken PNG").rgba.empty());
    assert(epochengine::platform_image_codec::decode_thumbnail(bytes.substr(0, 16)).rgba.empty());
}
